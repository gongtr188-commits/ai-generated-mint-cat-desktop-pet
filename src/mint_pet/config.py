"""全局可调常量。改数值前先看 docs/开发文档.md 的参数说明列。"""

FPS_MS = 80                 # 唯一驱动节拍；=12.5fps，与 24fps 素材 stride=2 对齐


def ticks(seconds: float) -> int:
    """秒 → tick 数。所有"多久"都按秒配，节拍只有 FPS_MS 一处，换算也只此一处。

    （以前 behavior.py 和 posture.py 各写了一份一模一样的 `_ticks`，
      stage 要用的时候眼看就是第三份了。）
    """
    return max(1, int(round(seconds * 1000 / FPS_MS)))

